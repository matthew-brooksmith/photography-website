#!/usr/bin/env python3
"""
Download Fraunces and Inter from Google Fonts into ./fonts/ and rewrite
./fonts.css to point at the local copies.

Run once, from the project folder:

    python3 tools/fetch-fonts.py

Then commit the fonts/ folder and fonts.css. After that the site makes no
third-party requests at all: no visitor IP address reaches Google, and the
Content Security Policy in index.html stays locked to 'self'.

Re-run it if you ever change which fonts or weights the site uses — edit
FAMILIES below first.

Needs nothing but a normal Python 3 install.
"""

import os
import re
import sys
import urllib.request
import urllib.error

# The families and weights style.css actually asks for.
FAMILIES = "family=Fraunces:opsz,wght@9..144,300;9..144,400&family=Inter:wght@400;500"
CSS_URL = f"https://fonts.googleapis.com/css2?{FAMILIES}&display=swap"

# Google serves different formats depending on the browser. Asking as a recent
# Chrome gets us woff2, which is what we want — smallest, universally supported.
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "fonts")
OUT_CSS = os.path.join(ROOT, "fonts.css")

HEADER = """/* ══════════════════════════════════════════════════════════════════════
   SELF-HOSTED FONTS — generated by tools/fetch-fonts.py. Don't hand-edit;
   re-run the script instead.

   These files are served from this site's own origin, so no visitor request
   ever reaches Google and the Content Security Policy needs no external
   origins. Commit this file together with the fonts/ folder.
   ══════════════════════════════════════════════════════════════════════ */

"""


def get(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = r.read()
    return data if binary else data.decode("utf-8")


def main():
    print(f"Fetching font CSS from Google…")
    try:
        css = get(CSS_URL)
    except urllib.error.URLError as e:
        sys.exit(f"Couldn't reach Google Fonts: {e}\nAre you online?")

    urls = sorted(set(re.findall(r"url\((https://fonts\.gstatic\.com/[^)]+)\)", css)))
    if not urls:
        sys.exit("No font files found in the response. Google may have changed "
                 "their API — check CSS_URL in this script.")

    os.makedirs(FONT_DIR, exist_ok=True)
    print(f"Downloading {len(urls)} font file(s) into fonts/ …")

    for url in urls:
        parts = [p for p in url.split("/") if p]
        family = parts[-3] if len(parts) >= 3 else "font"
        stem = parts[-1]
        name = re.sub(r"[^A-Za-z0-9._-]", "", f"{family}-{stem}")
        if not name.endswith(".woff2"):
            name += ".woff2"

        path = os.path.join(FONT_DIR, name)
        if not os.path.exists(path):
            with open(path, "wb") as fh:
                fh.write(get(url, binary=True))
            print(f"  + {name}")
        else:
            print(f"  = {name} (already here)")

        css = css.replace(url, f"fonts/{name}")

    with open(OUT_CSS, "w", encoding="utf-8") as fh:
        fh.write(HEADER + css.strip() + "\n")

    total = sum(os.path.getsize(os.path.join(FONT_DIR, f))
                for f in os.listdir(FONT_DIR)) / 1024
    print(f"\nWrote fonts.css and {len(os.listdir(FONT_DIR))} file(s) "
          f"({total:.0f} KB total).")
    print("Commit fonts.css and the fonts/ folder, and you're done.")


if __name__ == "__main__":
    main()
